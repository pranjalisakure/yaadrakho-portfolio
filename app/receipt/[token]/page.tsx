import PaymentInstructions from "../../PaymentInstructions";
import { notFound } from "next/navigation";
import { getPublicReceipt } from "../../../db/payment-receipts";
import PrintReceiptControls from "./PrintReceiptControls";

export const dynamic = "force-dynamic";

function money(amount: number) {
  return new Intl.NumberFormat("en-IN", { style: "currency", currency: "INR", maximumFractionDigits: 2 }).format(amount || 0);
}

function paidDate(value: number) {
  return new Intl.DateTimeFormat("en-IN", { timeZone: "Asia/Kolkata", day: "numeric", month: "short", year: "numeric", hour: "numeric", minute: "2-digit" }).format(new Date(value));
}

const methodNames: Record<string, string> = { cash: "Cash", upi: "UPI", paytm: "Paytm", bank: "Bank transfer", other: "Other" };

export default async function PaymentReceiptPage({ params, searchParams }: { params: Promise<{ token: string }>; searchParams: Promise<{ paper?: string }> }) {
  const receipt = await getPublicReceipt((await params).token);
  if (!receipt) notFound();
  const requestedPaper = String((await searchParams).paper || "a4");
  const paper = (["a4", "80mm", "58mm"].includes(requestedPaper) ? requestedPaper : "a4") as "a4" | "80mm" | "58mm";
  const paidInFull = receipt.balanceAfter === 0;
  const initial = receipt.businessName.charAt(0).toUpperCase() || "B";

  return <main className={`receipt-document receipt-paper-${paper}`}>
    <PrintReceiptControls paper={paper} receiptNumber={receipt.receiptNumber} />
    <article className="receipt-card">
      <header><span className="brand-mark">{initial}</span><div><small>RECEIVED BY</small><h1>{receipt.businessName}</h1>{receipt.businessPhone && <p>{receipt.businessPhone}</p>}</div></header>
      <section className="receipt-title"><div><small>PAYMENT RECEIPT</small><strong>{receipt.receiptNumber}</strong></div><span className={paidInFull ? "paid" : "partial"}>{paidInFull ? "PAID IN FULL" : "PART PAYMENT"}</span></section>
      <dl>
        <div><dt>Received from</dt><dd>{receipt.customerName}</dd></div>
        <div><dt>Customer phone</dt><dd>{receipt.customerPhone}</dd></div>
        <div><dt>Payment date</dt><dd>{paidDate(receipt.receivedAt)}</dd></div>
        <div><dt>Payment method</dt><dd>{methodNames[receipt.method] || receipt.method}</dd></div>
        {receipt.reference && <div><dt>Transaction reference</dt><dd>{receipt.reference}</dd></div>}
        {receipt.invoiceNumber && <div><dt>Against bill</dt><dd>{receipt.invoiceNumber}</dd></div>}
      </dl>
      <section className="receipt-amount"><small>AMOUNT RECEIVED</small><strong>{money(receipt.amount)}</strong><p>Balance after this payment: <b>{money(receipt.balanceAfter)}</b></p>{receipt.currentRemaining !== receipt.balanceAfter && <p>Current balance: <b>{money(receipt.currentRemaining)}</b></p>}</section>
      {!paidInFull && <PaymentInstructions token={receipt.billToken} remaining={receipt.currentRemaining} choice={receipt.remainingPayment} dueDate={receipt.dueDate} status={receipt.invoiceStatus} />}
      {receipt.note && <section className="receipt-note"><small>NOTE</small><p>{receipt.note}</p></section>}
      <footer><strong>Payment received successfully</strong><p>This digital receipt is payment proof generated by {receipt.businessName} through YaadRakho.</p></footer>
    </article>
  </main>;
}
