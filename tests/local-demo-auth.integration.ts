import assert from 'node:assert/strict';
import { rm } from 'node:fs/promises';
import { resolve } from 'node:path';
const file=resolve('backups/yaadrakho-local-auth-test.db');await rm(file,{force:true});
process.env.TURSO_DATABASE_URL='file:'+file.replaceAll('\\','/');delete process.env.TURSO_AUTH_TOKEN;
process.env.PUBLIC_APP_URL='http://127.0.0.1:3200';process.env.ALLOW_LOCAL_DEMO_AUTH='true';
delete process.env.VERCEL;delete process.env.VERCEL_ENV;delete process.env.RESEND_API_KEY;delete process.env.AUTH_EMAIL_FROM;
const {localDemoAuthEnabled}=await import('../app/local-demo-auth');
const {POST:signup}=await import('../app/api/auth/signup/route');
const {POST:forgot}=await import('../app/api/auth/forgot/route');
const {POST:login}=await import('../app/api/auth/login/route');
const {POST:confirm}=await import('../app/api/auth/password/confirm/route');
const {verifyEmailWithToken,findUserByEmail}=await import('../app/auth');
const {getClient}=await import('../db');
const request=(path:string,body:unknown)=>new Request('http://127.0.0.1:3200'+path,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});
const nativeFetch=globalThis.fetch;globalThis.fetch=async()=>{throw Error('No external delivery allowed in local demo');};
try {
 assert.equal(localDemoAuthEnabled(request('/login',{})),true);
 assert.equal(localDemoAuthEnabled(new Request('https://public.example.test')),false);
 assert.equal(localDemoAuthEnabled(new Request('http://localhost:3200/login')),true);
 assert.equal(localDemoAuthEnabled(new Request('http://localhost:3201/login')),false);
 process.env.VERCEL_ENV='production';assert.equal(localDemoAuthEnabled(),false);
 for(let i=0;i<5;i++)assert.equal((await signup(request('/api/auth/signup',{displayName:'Unavailable',email:'unavailable@example.test',password:'DemoPassword123!'}))).status,503);
 assert.equal(await findUserByEmail('unavailable@example.test'),null);
 const rate=await getClient().execute("SELECT COUNT(*) AS n FROM auth_requests WHERE request_key = 'signup:unavailable@example.test'");assert.equal(Number(rate.rows[0].n),0);
 assert.equal((await forgot(request('/api/auth/forgot',{email:'unavailable@example.test'}))).status,503);
 delete process.env.VERCEL_ENV;
 const created=await signup(request('/api/auth/signup',{displayName:'My Demo Shop',email:'shop@example.test',password:'DemoPassword123!'}));
 assert.equal(created.status,201);const data=await created.json();assert.ok(data.localDemoUrl);assert.ok(data.recoveryCode);
 assert.equal((await login(request('/api/auth/login',{email:'shop@example.test',password:'DemoPassword123!'}))).status,403);
 assert.equal(await verifyEmailWithToken(new URL(data.localDemoUrl).searchParams.get('token')!),true);
 assert.equal((await login(request('/api/auth/login',{email:'shop@example.test',password:'DemoPassword123!'}))).status,200);
 const reset=await forgot(request('/api/auth/forgot',{email:'shop@example.test'}));const resetData=await reset.json();assert.ok(resetData.localDemoUrl);
 const token=new URL(resetData.localDemoUrl).searchParams.get('token');
 assert.equal((await confirm(request('/api/auth/password/confirm',{token,password:'ChangedDemo123!'}))).status,200);
 assert.equal((await login(request('/api/auth/login',{email:'shop@example.test',password:'ChangedDemo123!'}))).status,200);
 assert.equal((await confirm(request('/api/auth/password/confirm',{token,password:'ReplayDemo123!'}))).status,400);
 process.env.VERCEL='1';assert.equal(localDemoAuthEnabled(),false);delete process.env.VERCEL;
 process.env.PUBLIC_APP_URL='https://public.example.test';assert.equal(localDemoAuthEnabled(),false);
 console.log('Local demo signup, verification, login, reset, single-use tokens, missing-provider preflight and deployment gates passed; no email or SMS sent');
}finally{globalThis.fetch=nativeFetch;await getClient().close();}
