import assert from "node:assert/strict";
import { rm } from "node:fs/promises";
import { resolve } from "node:path";
const target = resolve("backups/yaadrakho-sms-auth-test.db");
await rm(target, { force: true });
process.env.TURSO_DATABASE_URL = "file:" + target.replaceAll("\\", "/");
delete process.env.TURSO_AUTH_TOKEN;
process.env.SMS_OTP_ENABLED = "false";
const auth = await import("../app/auth");
const { startSmsChallenge, finishSmsChallenge, normalizeMobile } = await import("../app/sms-auth");
const { configuredSmsProvider, smsOtpAvailable } = await import("../app/sms-provider");
const { ensureAuthTables, getClient } = await import("../db");
await ensureAuthTables();
const db = getClient();
const account = await auth.registerUser({ email: "mobile@example.test", displayName: "Mobile Test", password: "OriginalPass123!" });
await auth.verifyEmailWithToken(await auth.createAccountToken(account.user.id, "verify_email", 60_000));
const actor = { ...account.user, emailVerified: true };
let sends = 0, checks = 0;
const provider = { async start() { sends++; return "VE" + "a".repeat(32); }, async verify(_phone: string, _sid: string, code: string) { checks++; return code === "123456"; } };
const clearLimits = () => db.execute("DELETE FROM auth_requests");
assert.equal(normalizeMobile("98765 43210"), "+919876543210");
assert.throws(() => normalizeMobile("+12025550123"));
assert.equal(smsOtpAvailable(), false);
assert.throws(() => configuredSmsProvider(), /not available/);
await assert.rejects(() => startSmsChallenge({ phone: "9876543210", purpose: "enroll", password: "OriginalPass123!" }, null, provider), /Sign in/);
await assert.rejects(() => startSmsChallenge({ phone: "9876543210", purpose: "enroll", password: "wrong" }, actor, provider), /current password/);
await clearLimits();
const enroll = await startSmsChallenge({ phone: "9876543210", purpose: "enroll", password: "OriginalPass123!" }, actor, provider);
await assert.rejects(() => finishSmsChallenge(enroll.challenge, "123456", "login", null, provider), /invalid/);
await assert.rejects(() => finishSmsChallenge(enroll.challenge, "123456", "enroll", { ...actor, id: actor.id + 1 }, provider), /invalid/);
assert.equal((await finishSmsChallenge(enroll.challenge, "123456", "enroll", actor, provider)).userId, actor.id);
await assert.rejects(() => finishSmsChallenge(enroll.challenge, "123456", "enroll", actor, provider), /already used/);
assert.equal((await db.execute("SELECT phone FROM account_phones")).rows[0].phone, "+919876543210");
const beforeUnknown = sends;
const unknown = await startSmsChallenge({ phone: "9876543211", purpose: "login" }, null, provider);
assert.equal(sends, beforeUnknown, "unlinked phones must not trigger SMS");
await assert.rejects(() => finishSmsChallenge(unknown.challenge, "123456", "login", null, provider), /invalid/);
await clearLimits();
const superseded = await startSmsChallenge({ phone: "9876543210", purpose: "login" }, null, provider);
const login = await startSmsChallenge({ phone: "9876543210", purpose: "login" }, null, provider);
await assert.rejects(() => finishSmsChallenge(superseded.challenge, "123456", "login", null, provider), /invalid/);
assert.equal((await finishSmsChallenge(login.challenge, "123456", "login", null, provider)).userId, actor.id);
await assert.rejects(() => finishSmsChallenge(login.challenge, "123456", "login", null, provider), /already used/);
await clearLimits();
const limited = await startSmsChallenge({ phone: "9876543210", purpose: "login" }, null, provider);
for (let i = 0; i < 5; i++) await assert.rejects(() => finishSmsChallenge(limited.challenge, "999999", "login", null, provider), /incorrect/);
const checksAfterLimit = checks;
await assert.rejects(() => finishSmsChallenge(limited.challenge, "123456", "login", null, provider), /invalid/);
assert.equal(checks, checksAfterLimit, "attempt limit must apply before contacting provider");
await clearLimits();
const oldEmailToken = await auth.createAccountToken(actor.id, "reset_password", 60_000);
await auth.createSession(actor.id, new Request("https://example.test"));
const reset = await startSmsChallenge({ phone: "9876543210", purpose: "reset" }, null, provider);
const approved = await finishSmsChallenge(reset.challenge, "123456", "reset", null, provider);
assert.ok(approved.resetToken);
assert.equal(await auth.replacePasswordWithToken(oldEmailToken, "RejectedPass123!"), null, "new SMS reset must invalidate older reset link");
const result = await auth.replacePasswordWithToken(approved.resetToken!, "NewPassword123!");
assert.equal(result?.userId, actor.id);
assert.equal((await db.execute("SELECT COUNT(*) AS n FROM sessions")).rows[0].n, 0, "reset revokes old sessions");
assert.equal(await auth.replacePasswordWithToken(approved.resetToken!, "ReplayPassword123!"), null);
assert.equal(await auth.verifyUserPassword((await auth.findUserByEmail(actor.email))!, "NewPassword123!"), true);
await clearLimits();
const changed = await startSmsChallenge({ phone: "9876543210", purpose: "login" }, null, provider);
const staleReset = await auth.createAccountToken(actor.id, "reset_password", 60_000);
await auth.replacePassword(actor.id, "FinalPassword123!");
await assert.rejects(() => finishSmsChallenge(changed.challenge, "123456", "login", null, provider), /invalid/);
assert.equal(await auth.replacePasswordWithToken(staleReset, "UnsafeOldToken123!"), null, "recovery-code reset must invalidate old email tokens too");
await clearLimits();
const expired = await startSmsChallenge({ phone: "9876543210", purpose: "login" }, null, provider);
await db.execute("UPDATE sms_challenges SET expires_at = 1");
await assert.rejects(() => finishSmsChallenge(expired.challenge, "123456", "login", null, provider), /expired/);
await clearLimits();
const allowed = await Promise.all(Array.from({ length: 8 }, () => auth.checkAuthRequestLimit("concurrent-test", "one")));
assert.equal(allowed.filter(Boolean).length, 3, "concurrent requests cannot bypass send limits");
await Promise.all(Array.from({ length: 8 }, () => auth.recordFailedLogin(actor.email)));
assert.ok(await auth.checkLoginRateLimit(actor.email) > 0, "concurrent wrong passwords must trigger lockout");
await auth.clearFailedLogins(actor.email);
assert.equal(await auth.checkLoginRateLimit(actor.email), 0);
await clearLimits();
const second = await auth.registerUser({ email: "second-mobile@example.test", displayName: "Second", password: "SecondPass123!" });
await auth.verifyEmailWithToken(await auth.createAccountToken(second.user.id, "verify_email", 60_000));
await assert.rejects(() => startSmsChallenge({ phone: "9876543210", purpose: "enroll", password: "SecondPass123!" }, { ...second.user, emailVerified: true }, provider), /cannot be linked/);
await clearLimits();
const beforePhoneChange = await auth.createAccountToken(actor.id, "reset_password", 60_000);
const newPhone = await startSmsChallenge({ phone: "9876543212", purpose: "enroll", password: "FinalPassword123!" }, actor, provider);
await finishSmsChallenge(newPhone.challenge, "123456", "enroll", actor, provider);
assert.equal(await auth.replacePasswordWithToken(beforePhoneChange, "OldPhoneReset123!"), null, "phone change revokes outstanding reset links");
const sendCount = sends;
await startSmsChallenge({ phone: "9876543210", purpose: "login" }, null, provider);
assert.equal(sends, sendCount, "previous phone must no longer receive login codes");
// Provider adapter checks identities as well as approved status; no real SMS is sent.
process.env.SMS_OTP_ENABLED = "true"; process.env.SMS_OTP_PROVIDER = "twilio_verify";
process.env.TWILIO_ACCOUNT_SID = "AC" + "a".repeat(32); process.env.TWILIO_VERIFY_SERVICE_SID = "VA" + "b".repeat(32); process.env.TWILIO_AUTH_TOKEN = "synthetic-test-secret";
const sid = "VE" + "c".repeat(32), phone = "+919876543210";
const sms = configuredSmsProvider((async (url: RequestInfo | URL, init?: RequestInit) => {
 assert.equal(init?.method, "POST");
 return Response.json({ sid, service_sid: process.env.TWILIO_VERIFY_SERVICE_SID, to: phone, status: String(url).endsWith("VerificationCheck") ? "approved" : "pending" });
}) as typeof fetch);
assert.equal(await sms.start(phone), sid);
assert.equal(await sms.verify(phone, sid, "123456"), true);
assert.equal(await sms.verify("+919876543211", sid, "123456"), false);
console.log("SMS auth passed: disabled gate, phone ownership, purpose binding, replay/expiry/attempt limits, login, reset, stale credential revocation, concurrent send limits and provider identity checks; no SMS sent");
await db.close();
